

$(function(){
        var TCDZeroSlider; 
        var TCDNextBtn = $('.tc-right1'); 
        var TCDNPrevBtn = $('.tc-left1'); 
        setTimeout(function(){ TCDZeroSlider = $('.tc-gallery1'); 
        }, 1000); 
        
        TCDNextBtn.click(function(){
        TCDZeroSlider.find('[data-slide-direction="right"]').click(); }); 
        TCDNPrevBtn.click(function(){ TCDZeroSlider.find('[data-slide-direction="left"]').click(); });
}); 

